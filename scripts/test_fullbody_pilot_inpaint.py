#!/usr/bin/env python3
"""
Isolated Full-Body Identity-Preserved Avatar Inpainting Prototype
------------------------------------------------------------------
Uses verified raw full-body webcam capture:
  public/captured/input_1794834000206_a2l851.png (1080x1920)

Strict Rules:
- Head, hair, face, and natural facial features are protected (Mask = 0).
- Entire clothing from collar down to trousers and shoes is generated by diffusion (Mask = 255).
- No pre-rendered 2D body template or clipart is used.
- Preserves the user's authentic body proportions and standing pose.
- Outputs saved strictly to: test_outputs/prototype/
- Zero changes to production files.
"""

import os
import sys
import time
import gc
import psutil
import numpy as np
from PIL import Image, ImageOps, ImageDraw, ImageFilter
import torch

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

OUTPUT_DIR = os.path.join(PROJECT_ROOT, "test_outputs", "prototype")
os.makedirs(OUTPUT_DIR, exist_ok=True)

INPUT_PHOTO = os.path.join(PROJECT_ROOT, "public", "captured", "input_1794834000206_a2l851.png")

def get_sys_memory_mb():
    return psutil.Process().memory_info().rss / (1024 * 1024)

def get_vram_mb():
    if torch.cuda.is_available():
        return torch.cuda.max_memory_allocated() / (1024 * 1024)
    return 0.0

def reset_cuda():
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
        torch.cuda.reset_peak_memory_stats()

print("=" * 70)
print("  FULL-BODY IDENTITY-PRESERVED AVATAR INPAINTING PROTOTYPE")
print("=" * 70)
print(f"CUDA Available: {torch.cuda.is_available()}")
if torch.cuda.is_available():
    print(f"Device: {torch.cuda.get_device_name(0)}")
print(f"Input Photo: {INPUT_PHOTO}")
print(f"Output Directory: {OUTPUT_DIR}\n")

reset_cuda()
ram_init = get_sys_memory_mb()

# ---------------------------------------------------------------------
# Step 1: Load and analyze raw full-body photograph
# ---------------------------------------------------------------------
print("[Step 1/5] Loading raw webcam capture and detecting landmarks...")
raw_img = Image.open(INPUT_PHOTO).convert('RGB')
rw, rh = raw_img.size

from scripts.face_identity import ArcFaceAnalyzer, extract_user_pose_landmarks
analyzer = ArcFaceAnalyzer()
faces = analyzer.detect_faces(raw_img)
if not faces:
    raise RuntimeError("No face detected in input photo!")

face_info = faces[0]
fb = face_info['bbox']
fx1, fy1, fx2, fy2 = fb
face_w = fx2 - fx1
face_h = fy2 - fy1
face_cx = (fx1 + fx2) / 2.0
face_cy = (fy1 + fy2) / 2.0
print(f"  Face detected: BBox=[{fx1:.1f}, {fy1:.1f}, {fx2:.1f}, {fy2:.1f}], Size={face_w:.1f}x{face_h:.1f}")

# Extract pose landmarks for full body
lms = extract_user_pose_landmarks(raw_img)
if lms:
    ankle_l_y = lms[27].y * rh
    ankle_r_y = lms[28].y * rh
    foot_l_y = lms[31].y * rh
    foot_r_y = lms[32].y * rh
    feet_bot_y = max(foot_l_y, foot_r_y, ankle_l_y, ankle_r_y)
    print(f"  Feet detected at Y = {feet_bot_y:.1f} px (Ankles: {ankle_l_y:.1f}, {ankle_r_y:.1f})")
else:
    feet_bot_y = 1910.0
    print(f"  Pose landmarks fallback: Feet estimated at Y = {feet_bot_y:.1f} px")

# Head top and full-body bounding box in original coordinates
head_top_y = max(0, int(fy1 - face_h * 0.45))
crop_bot_y = min(rh, int(feet_bot_y + 10))

# Crop width: center around person with natural margins
body_h = crop_bot_y - head_top_y
body_w_est = int(body_h * 0.42)
crop_x1 = max(0, int(face_cx - body_w_est * 0.65))
crop_x2 = min(rw, int(face_cx + body_w_est * 0.65))
crop_w = crop_x2 - crop_x1
crop_h = crop_bot_y - head_top_y

print(f"  Full-body bounding crop: [{crop_x1}, {head_top_y}, {crop_x2}, {crop_bot_y}] ({crop_w}x{crop_h} px)")

body_crop = raw_img.crop((crop_x1, head_top_y, crop_x2, crop_bot_y))

# Add 30px floor padding below feet so shoe soles and shadows generate cleanly
pad_bottom = 36
padded_w = crop_w
padded_h = crop_h + pad_bottom
padded_body = Image.new('RGB', (padded_w, padded_h), (255, 255, 255))
padded_body.paste(body_crop, (0, 0))

# Resize to standard diffusion inpainting canvas: 512 x 896 (9:15.75 aspect ratio, optimal for SD 1.5)
DIFF_W, DIFF_H = 512, 896
diff_input = padded_body.resize((DIFF_W, DIFF_H), Image.Resampling.LANCZOS)

out_crop_path = os.path.join(OUTPUT_DIR, "fullbody_01_raw_cropped_input.png")
diff_input.save(out_crop_path)
print(f"  Saved cropped diffusion input: {out_crop_path}")


# ---------------------------------------------------------------------
# Step 2: Build high-precision clothing & face-protection mask
# ---------------------------------------------------------------------
print("\n[Step 2/5] Constructing full-body clothing inpainting mask...")
# In diffusion canvas coordinates:
scale_x = DIFF_W / float(padded_w)
scale_y = DIFF_H / float(padded_h)

# Chin / collar level:
chin_y_orig = fy2 - head_top_y
neck_y_diff = int((chin_y_orig + face_h * 0.12) * scale_y)
face_cx_diff = int((face_cx - crop_x1) * scale_x)
face_w_diff = int(face_w * scale_x)

inpaint_mask = Image.new('L', (DIFF_W, DIFF_H), 0)
mask_draw = ImageDraw.Draw(inpaint_mask)

# Target: Everything from neck down to feet is REGENERATED (255)
mask_draw.rectangle([0, neck_y_diff, DIFF_W, DIFF_H], fill=255)

# Collar scoop around neck for natural shirt/tie transition
scoop_w = int(face_w_diff * 1.35)
mask_draw.ellipse([face_cx_diff - scoop_w // 2, neck_y_diff - 12, face_cx_diff + scoop_w // 2, neck_y_diff + 24], fill=255)

# STRICT FACIAL & HAIR PROTECTION: Everything above collar scoop is strictly protected (0)
mask_draw.rectangle([0, 0, DIFF_W, neck_y_diff - 14], fill=0)

# Smooth boundary feather (3.5px) to ensure zero hard cut lines
feathered_mask = inpaint_mask.filter(ImageFilter.GaussianBlur(3.5))

out_mask_path = os.path.join(OUTPUT_DIR, "fullbody_02_inpaint_mask.png")
feathered_mask.save(out_mask_path)
print(f"  Protected: Head, hair, face, eyes, lips, jawline (Y < {neck_y_diff} in diffusion space)")
print(f"  Regenerated: Blazer, shirt, tie, trousers, ankles, and shoes (Y >= {neck_y_diff})")
print(f"  Saved mask: {out_mask_path}")


# ---------------------------------------------------------------------
# Step 3: Run Full-Body Diffusion Inpainting on CUDA
# ---------------------------------------------------------------------
print("\n[Step 3/5] Executing full-body diffusion inpainting on GPU...")
from diffusers import StableDiffusionInpaintPipeline, DPMSolverMultistepScheduler

device = "cuda" if torch.cuda.is_available() else "cpu"
torch.cuda.reset_peak_memory_stats()

pipe = StableDiffusionInpaintPipeline.from_pretrained(
    "runwayml/stable-diffusion-inpainting",
    torch_dtype=torch.float16 if device == "cuda" else torch.float32,
    variant="fp16" if device == "cuda" else None,
    safety_checker=None
)
pipe.scheduler = DPMSolverMultistepScheduler.from_config(pipe.scheduler.config)

if device == "cuda":
    pipe.enable_attention_slicing("auto")
    pipe.enable_vae_slicing()
    pipe.enable_vae_tiling()
    pipe.enable_model_cpu_offload()

pilot_fullbody_prompt = (
    "photorealistic official studio portrait photograph of an adult airline captain pilot head to feet, "
    "standing straight upright, tailored dark navy blue double-breasted pilot blazer with polished brass buttons, "
    "gold 4-stripe captain braid epaulettes on cuffs, white collared shirt, black necktie, "
    "tailored dark navy uniform trousers, polished black leather shoes, professional studio lighting, pure clean white background"
)

pilot_fullbody_neg = (
    "face, head, hair, eyes, mouth, chin, naked, doctor, scrubs, stethoscope, astronaut, "
    "deformed legs, missing feet, bad anatomy, deformed shoes, floating buttons, "
    "cartoon, 3d, illustration, dirty clothes, background clutter, dark background, blurry"
)

t_start = time.time()
with torch.inference_mode():
    diff_raw = pipe(
        prompt=pilot_fullbody_prompt,
        negative_prompt=pilot_fullbody_neg,
        image=diff_input,
        mask_image=feathered_mask,
        height=DIFF_H,
        width=DIFF_W,
        num_inference_steps=25,
        guidance_scale=7.5,
        generator=torch.Generator(device=device).manual_seed(314)
    ).images[0]

if diff_raw.size != (DIFF_W, DIFF_H):
    diff_raw = diff_raw.resize((DIFF_W, DIFF_H), Image.Resampling.LANCZOS)

duration = time.time() - t_start
peak_vram = get_vram_mb()
peak_ram = get_sys_memory_mb()

out_raw_path = os.path.join(OUTPUT_DIR, "fullbody_03_diffusion_generated_raw.png")
diff_raw.save(out_raw_path)
print(f"  Diffusion inpainting completed in {duration:.2f}s!")
print(f"  Peak VRAM: {peak_vram:.1f} MB | Peak RAM: {peak_ram:.1f} MB")
print(f"  Saved raw inpaint output: {out_raw_path}")


# ---------------------------------------------------------------------
# Step 4: Alpha blend protected original face + diffusion clothing
# ---------------------------------------------------------------------
print("\n[Step 4/5] Compositing protected facial features with diffusion clothing...")
mask_arr = np.array(feathered_mask).astype(np.float32) / 255.0
orig_arr = np.array(diff_input).astype(np.float32)
diff_arr = np.array(diff_raw).astype(np.float32)

fused_arr = (orig_arr * (1.0 - mask_arr[:, :, None]) + diff_arr * mask_arr[:, :, None]).clip(0, 255).astype(np.uint8)
fused_fullbody = Image.fromarray(fused_arr)


# ---------------------------------------------------------------------
# Step 5: Studio Matting & Pure White Holobox 1080x1920 Canvas
# ---------------------------------------------------------------------
print("\n[Step 5/5] Compositing onto 1080x1920 Holobox Chamber Canvas with floor contact shadows...")
from scripts.ai_transform import AIStudioEngine
engine = AIStudioEngine()
engine._ensure_u2net()

# Extract clean person silhouette
person_matte = engine.extract_person_matte(fused_fullbody)
from scipy.ndimage import gaussian_filter
smooth_alpha = gaussian_filter(person_matte.astype(np.float32) / 255.0, sigma=1.0)
solid_mask = person_matte > 190
smooth_alpha[solid_mask] = 1.0
alpha_pil = Image.fromarray((np.clip(smooth_alpha, 0, 1) * 255).astype(np.uint8), mode='L')

fused_rgba = fused_fullbody.convert('RGBA')
fused_rgba.putalpha(alpha_pil)

# High-resolution Holobox 1080x1920 Pure White Canvas
CANVAS_W, CANVAS_H = 1080, 1920
holobox_canvas = Image.new('RGB', (CANVAS_W, CANVAS_H), (255, 255, 255))

# Scale to natural human height inside Holobox: ~1620 px tall (head at Y=160, feet at Y=1780)
TARGET_HEIGHT = 1620
scale_final = TARGET_HEIGHT / float(DIFF_H)
final_w = int(DIFF_W * scale_final)
final_h = TARGET_HEIGHT

scaled_subject = fused_rgba.resize((final_w, final_h), Image.Resampling.LANCZOS)
pos_x = (CANVAS_W - final_w) // 2
pos_y = 1780 - final_h

# Draw realistic soft floor contact shadow under shoes
shadow_layer = Image.new('RGBA', (CANVAS_W, CANVAS_H), (0, 0, 0, 0))
s_draw = ImageDraw.Draw(shadow_layer)
shoe_cx = CANVAS_W // 2
shoe_cy = 1775
# Dual elliptical contact shadows for left and right foot
s_draw.ellipse([shoe_cx - 160, shoe_cy - 12, shoe_cx - 20, shoe_cy + 18], fill=(30, 41, 59, 140))
s_draw.ellipse([shoe_cx + 20, shoe_cy - 12, shoe_cx + 160, shoe_cy + 18], fill=(30, 41, 59, 140))
# Broader soft ambient ground shadow
s_draw.ellipse([shoe_cx - 240, shoe_cy - 20, shoe_cx + 240, shoe_cy + 30], fill=(71, 85, 105, 70))

shadow_blurred = shadow_layer.filter(ImageFilter.GaussianBlur(8))
holobox_canvas.paste(shadow_blurred, (0, 0), shadow_blurred)

# Paste scaled subject onto canvas
holobox_canvas.paste(scaled_subject, (pos_x, pos_y), scaled_subject)

out_final_path = os.path.join(OUTPUT_DIR, "fullbody_04_final_holobox_1080x1920.png")
holobox_canvas.save(out_final_path)
print(f"  Final 1080x1920 Holobox image saved: {out_final_path}")


# ---------------------------------------------------------------------
# Biometric ArcFace Similarity Verification
# ---------------------------------------------------------------------
print("\n" + "=" * 60)
print("  BIOMETRIC IDENTITY & FIDELITY EVALUATION")
print("=" * 60)
id_orig = analyzer.extract_identity(raw_img)
sim = analyzer.verify_similarity(id_orig['embedding'], holobox_canvas)
print(f"  ArcFace Cosine Similarity (Original vs Generated): {sim:.4f}")

# Build Side-by-Side Comparison Panel
comp_w = 1080 * 2
comp_h = 1920
side_by_side = Image.new('RGB', (comp_w, comp_h), (245, 247, 250))

# Left: Original full-body capture
orig_fit = ImageOps.fit(raw_img, (1080, 1920), Image.Resampling.LANCZOS)
side_by_side.paste(orig_fit, (0, 0))

# Right: Full-body diffusion pilot
side_by_side.paste(holobox_canvas, (1080, 0))

# Add clean header bar
banner = Image.new('RGBA', (comp_w, 90), (15, 23, 42, 235))
b_draw = ImageDraw.Draw(banner)
b_draw.text((80, 30), "ORIGINAL WEBCAM FULL-BODY CAPTURE", fill=(255, 255, 255))
b_draw.text((1160, 30), "DIFFUSION FULL-BODY PILOT (ZERO 2D TEMPLATES)", fill=(56, 189, 248))
side_by_side.paste(banner, (0, 0), banner)

out_comp_path = os.path.join(OUTPUT_DIR, "fullbody_05_side_by_side_comparison.png")
side_by_side.save(out_comp_path)
print(f"  Saved side-by-side comparison panel: {out_comp_path}")

print("\n" + "=" * 70)
print("  FULL-BODY EXPERIMENT COMPLETE")
print("=" * 70)
print(f"  Status: PASS")
print(f"  Generation Time: {duration:.2f}s")
print(f"  Peak VRAM: {peak_vram:.1f} MB ({peak_vram / 1024:.2f} GB)")
print(f"  Peak RAM: {peak_ram:.1f} MB ({peak_ram / 1024:.2f} GB)")
print(f"  ArcFace Identity Score: {sim:.4f}")
